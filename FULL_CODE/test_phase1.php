<?php
/**
 * Automated Verification Suite for Phase 1
 * Medication Safety Second Pair of Eyes
 * CLI & Browser Compatible
 */

declare(strict_types=1);

require_once __DIR__ . '/config/config.php';
require_once __DIR__ . '/includes/helpers.php';
require_once __DIR__ . '/includes/Database.php';
require_once __DIR__ . '/models/Patient.php';
require_once __DIR__ . '/models/Medication.php';

$isCli = (php_sapi_name() === 'cli');

class Phase1TestSuite
{
    private bool $isCli;
    private int $passed = 0;
    private int $failed = 0;
    private array $results = [];

    public function __construct(bool $isCli)
    {
        $this->isCli = $isCli;
    }

    public function assert(string $name, bool $condition, string $detail = ''): void
    {
        if ($condition) {
            $this->passed++;
            $this->results[] = ['name' => $name, 'status' => 'PASS', 'detail' => $detail];
            if ($this->isCli) {
                echo "[PASS] {$name}" . ($detail ? " ({$detail})" : "") . PHP_EOL;
            }
        } else {
            $this->failed++;
            $this->results[] = ['name' => $name, 'status' => 'FAIL', 'detail' => $detail];
            if ($this->isCli) {
                echo "[FAIL] {$name}" . ($detail ? " ({$detail})" : "") . PHP_EOL;
            }
        }
    }

    public function run(): void
    {
        if ($this->isCli) {
            echo "========================================================" . PHP_EOL;
            echo "  MEDICATION SAFETY SECOND PAIR OF EYES - PHASE 1 TESTS  " . PHP_EOL;
            echo "========================================================" . PHP_EOL;
        }

        // Test 1: Configuration & Mandatory Clinical Disclaimer
        $this->assert(
            'Mandatory Clinical Disclaimer defined',
            defined('CLINICAL_DISCLAIMER') && str_contains(CLINICAL_DISCLAIMER, 'All alerts and recommendations require professional review'),
            'Requirement 7: Clinical Safety Disclaimer active'
        );

        // Test 2: Database Connection
        try {
            $pdo = Database::getInstance()->getConnection();
            $this->assert('Database Connection', $pdo instanceof PDO, 'Connected with UTF8mb4 & PDO::ERRMODE_EXCEPTION');
        } catch (Exception $e) {
            $this->assert('Database Connection', false, $e->getMessage());
            return;
        }

        // Test 3: Schema Verification
        $requiredTables = [
            'patients', 'medicines', 'medicine_aliases', 'drug_interactions',
            'patient_medications', 'safety_rules', 'safety_alerts',
            'evaluation_cases', 'import_logs'
        ];
        $stmt = $pdo->query("SHOW TABLES");
        $existingTables = $stmt->fetchAll(PDO::FETCH_COLUMN);

        foreach ($requiredTables as $tbl) {
            $this->assert("Table exists: {$tbl}", in_array($tbl, $existingTables, true));
        }

        // Test 4: KDIGO Renal Stage Calculation
        $this->assert('KDIGO eGFR Normal (95)', getEgfrStage(95.0)['stage'] === 'G1');
        $this->assert('KDIGO eGFR Mild (75)', getEgfrStage(75.0)['stage'] === 'G2');
        $this->assert('KDIGO eGFR Moderate-Severe (35)', getEgfrStage(35.0)['stage'] === 'G3b');
        $this->assert('KDIGO eGFR Severe Impairment (25)', getEgfrStage(25.0)['stage'] === 'G4');
        $this->assert('KDIGO eGFR Kidney Failure (10)', getEgfrStage(10.0)['stage'] === 'G5');
        $this->assert('KDIGO eGFR Unknown handled', getEgfrStage(null)['stage'] === 'Unknown');

        // Test 5: Seed Data Integrity
        $patientModel = new Patient();
        $stats = $patientModel->getStats();
        $this->assert('Seeded Patients Count >= 6', $stats['total_patients'] >= 6, "Found {$stats['total_patients']}");
        $this->assert('Renal Impaired Patients Identified', $stats['renal_risk_patients'] >= 2, "Found {$stats['renal_risk_patients']}");
        $this->assert('Seeded Near-Miss Cases Flagged', $stats['near_miss_cases'] >= 3, "Found {$stats['near_miss_cases']}");
        $this->assert('Multi-Doctor Patients Identified', $stats['multi_doctor_patients'] >= 2, "Found {$stats['multi_doctor_patients']}");

        // Test 6: Patient Model CRUD & Validation
        $testMrn = 'TEST-VERIFY-' . time();
        $testPatientData = [
            'patient_mrn' => $testMrn,
            'full_name' => 'Automated Test Patient',
            'date_of_birth' => '1965-05-15',
            'gender' => 'female',
            'egfr' => '29.5',
            'serum_creatinine' => '2.1',
            'conditions' => 'Type 2 Diabetes, CKD Stage 4',
            'allergies' => 'Penicillin',
            'is_near_miss_case' => 1,
            'notes' => 'Generated by Phase 1 test suite'
        ];

        // Validation test
        $errors = $patientModel->validate($testPatientData);
        $this->assert('Patient Validation with Valid Data', empty($errors));

        // Create
        $newPatientId = $patientModel->create($testPatientData);
        $this->assert('Patient Creation', $newPatientId > 0, "Inserted ID: {$newPatientId}");

        // Read
        $retrieved = $patientModel->getById($newPatientId);
        $this->assert('Patient Retrieval by ID', $retrieved !== null && $retrieved['patient_mrn'] === $testMrn);

        // Update
        $testPatientData['full_name'] = 'Updated Test Patient';
        $testPatientData['egfr'] = '24.0';
        $updateSuccess = $patientModel->update($newPatientId, $testPatientData);
        $this->assert('Patient Profile Update', $updateSuccess);

        $retrievedAfterUpdate = $patientModel->getById($newPatientId);
        $this->assert('Patient Update Verified', $retrievedAfterUpdate['full_name'] === 'Updated Test Patient' && (float)$retrievedAfterUpdate['egfr'] === 24.0);

        // Test 7: Medication Model Multi-Doctor Timeline & CRUD
        $medicationModel = new Medication();
        $refMeds = $medicationModel->getReferenceMedicines();
        $this->assert('Reference Medicines Available', count($refMeds) >= 5, "Found " . count($refMeds));

        $testMedData1 = [
            'patient_id' => $newPatientId,
            'medicine_id' => $refMeds[0]['id'] ?? 1,
            'raw_medicine_name' => 'Glucophage 1000mg',
            'dosage' => '1000 mg',
            'dose_amount_mg' => 1000.0,
            'frequency' => 'BID',
            'route' => 'oral',
            'prescribing_doctor' => 'Dr. Alpha (Primary Care)',
            'prescription_date' => '2021-06-01',
            'start_date' => '2021-06-01',
            'status' => 'active',
            'indication' => 'Glycemic Control'
        ];
        $medId1 = $medicationModel->create($testMedData1);

        $testMedData2 = [
            'patient_id' => $newPatientId,
            'medicine_id' => $refMeds[1]['id'] ?? 2,
            'raw_medicine_name' => 'Zestril 20mg',
            'dosage' => '20 mg',
            'dose_amount_mg' => 20.0,
            'frequency' => 'Once daily',
            'route' => 'oral',
            'prescribing_doctor' => 'Dr. Beta (Cardiology)',
            'prescription_date' => '2023-08-15',
            'start_date' => '2023-08-15',
            'status' => 'active',
            'indication' => 'Hypertension'
        ];
        $medId2 = $medicationModel->create($testMedData2);

        $this->assert('Multi-Doctor Medications Inserted', $medId1 > 0 && $medId2 > 0);

        // Verify timeline ordering
        $timeline = $medicationModel->getTimelineByPatientId($newPatientId);
        $this->assert('Timeline Count', count($timeline) === 2);
        $this->assert('Timeline Chronological Order', $timeline[0]['prescription_date'] <= $timeline[1]['prescription_date']);

        // Verify status update (discontinue)
        $medicationModel->updateStatus($medId1, 'discontinued');
        $updatedMed = $medicationModel->getById($medId1);
        $this->assert('Medication Discontinuation Status', $updatedMed['status'] === 'discontinued');

        // Test 8: Clean up test patient (cascade delete)
        $patientModel->delete($newPatientId);
        $deletedPt = $patientModel->getById($newPatientId);
        $this->assert('Cascade Patient Deletion Clean-up', $deletedPt === null);

        // Test 9: Citizen Experience, Authentication & Safety Percentage Engine
        $tableCheckUsers = $pdo->query("SHOW TABLES LIKE 'users'")->fetch();
        $this->assert('Table exists: users (Citizen Auth)', !empty($tableCheckUsers));

        $userCount = (int)$pdo->query("SELECT COUNT(*) FROM users")->fetchColumn();
        $this->assert('Citizen Demo Accounts Seeded', $userCount >= 4, "Found {$userCount} accounts");

        $scoreClean = calculateSafetyScore([]);
        $this->assert('Safety Score Formula: Clean Regimen', $scoreClean['score'] >= 95, "Calculated {$scoreClean['score']}%");

        $mockHighAlert = [['severity' => 'high', 'problem' => 'Bleeding', 'why_flagged' => '', 'recommended_action' => '']];
        $scoreHigh = calculateSafetyScore($mockHighAlert);
        $this->assert('Safety Score Formula: High Risk Alert Penalty', $scoreHigh['score'] <= 60, "Calculated {$scoreHigh['score']}%");

        $mockCritAlert = [['severity' => 'critical', 'problem' => 'Fatal lactic acidosis', 'why_flagged' => '', 'recommended_action' => '']];
        $scoreCrit = calculateSafetyScore($mockCritAlert);
        $this->assert('Safety Score Formula: Critical Risk Alert Penalty', $scoreCrit['score'] <= 30, "Calculated {$scoreCrit['score']}%");

        $this->assert('496+ Reference Medicines Catalog Available', count($refMeds) >= 496, "Found " . count($refMeds) . " catalog drugs");

        // Test 10: Access Control & Cross-Patient Medication Isolation (IDOR Protection)
        logoutUser();
        $this->assert('Guest Denied Medication Management', !canManagePatient(1) && !canManagePatient(2));

        loginUser(['id' => 1, 'patient_id' => 1, 'email' => 'eleanor@example.com', 'full_name' => 'Eleanor Vance', 'role' => 'citizen']);
        $this->assert('Citizen Can Manage Own Medications (Patient 1)', canManagePatient(1));
        $this->assert('Citizen BLOCKED from Modifying Another Patient (Patient 2)', !canManagePatient(2));
        $this->assert('Citizen BLOCKED from Viewing Another Patient Chart (Patient 2)', !canViewPatient(2));

        loginUser(['id' => 5, 'patient_id' => null, 'email' => 'admin@dosewise.com', 'full_name' => 'Dr. Sarah Jenkins', 'role' => 'admin']);
        $this->assert('Admin Authorized to Manage All Patients', canManagePatient(1) && canManagePatient(2));
        $this->assert('Admin Authorized to View All Patient Charts', canViewPatient(1) && canViewPatient(2));

        // Clean up session after tests
        logoutUser();

        // Summary
        if ($this->isCli) {
            echo "--------------------------------------------------------" . PHP_EOL;
            echo "SUMMARY: {$this->passed} Passed, {$this->failed} Failed." . PHP_EOL;
            if ($this->failed === 0) {
                echo "[ALL TESTS PASSED] Phase 1 architecture is robust and verified!" . PHP_EOL;
            }
            echo "========================================================" . PHP_EOL;
        }
    }

    public function getResults(): array
    {
        return [
            'passed' => $this->passed,
            'failed' => $this->failed,
            'tests' => $this->results
        ];
    }
}

$suite = new Phase1TestSuite($isCli);
$suite->run();

